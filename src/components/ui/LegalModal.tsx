import { X } from 'lucide-react';
import { GlassButton, GlassCard } from './GlassPrimitives';

export function LegalModal({
  type,
  onClose,
}: {
  type: 'terms' | 'privacy' | null;
  onClose: () => void;
}) {
  if (!type) return null;

  const isTerms = type === 'terms';

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 p-4 backdrop-blur-sm"
      role="dialog"
      aria-modal="true"
      aria-labelledby="legal-modal-title"
    >
      <GlassCard className="w-full max-w-lg p-6" withRefraction>
        <div className="flex items-center justify-between gap-4 border-b border-white/10 pb-4">
          <div>
            <h2 id="legal-modal-title" className="text-lg font-semibold text-white">
              {isTerms ? 'Terms of Service' : 'Privacy Policy'}
            </h2>
            <p className="text-xs text-[#9ca2b8]">Placeholder legal notice for IDEONIX preview</p>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close modal"
            className="inline-flex h-10 w-10 items-center justify-center rounded-xl border border-white/10 bg-white/[0.04] text-[#b8bcd0] hover:bg-white/[0.1] hover:text-white"
          >
            <X className="h-4 w-4" aria-hidden="true" />
          </button>
        </div>
        <div className="mt-4 space-y-3 text-sm leading-relaxed text-[#b8bcd0]">
          {isTerms ? (
            <>
              <p>
                IDEONIX provides AI-assisted content planning, scripting, captioning, and scheduling
                workflows. Outputs generated by AI models are editorial suggestions and should be
                reviewed before publication.
              </p>
              <p>
                Viral Analyzer scores are AI-generated estimates based on structural heuristics and
                are not predictions or guarantees of social media reach.
              </p>
            </>
          ) : (
            <>
              <p>
                When signed in with Firebase Authentication, your saved library items, brand voice
                preferences, campaigns, and calendar entries are stored under your user account in
                Cloud Firestore.
              </p>
              <p>
                In Local Demo Mode, data stays strictly in your browser&apos;s localStorage. Server-side
                Gemini API requests are processed through IDEONIX API routes without exposing keys
                to the browser.
              </p>
            </>
          )}
        </div>
        <div className="mt-6 flex justify-end">
          <GlassButton onClick={onClose}>Close</GlassButton>
        </div>
      </GlassCard>
    </div>
  );
}
