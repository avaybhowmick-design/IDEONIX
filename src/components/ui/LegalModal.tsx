import { AnimatePresence, motion } from 'motion/react';
import { X } from 'lucide-react';
import { GlassButton, GlassCard } from './GlassPrimitives';
import {
  getModalBackdropVariants,
  getModalDialogVariants,
  MOTION_EASING,
  useMotionSettings,
} from '../../config/motion';

export function LegalModal({
  type,
  onClose,
}: {
  type: 'terms' | 'privacy' | null;
  onClose: () => void;
}) {
  const { durations } = useMotionSettings();
  const isTerms = type === 'terms';

  return (
    <AnimatePresence>
      {type && (
        <motion.div
          key="legal-modal-backdrop"
          variants={getModalBackdropVariants(durations.base)}
          initial="initial"
          animate="animate"
          exit="exit"
          onClick={onClose}
          className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 p-4 backdrop-blur-sm"
          role="dialog"
          aria-modal="true"
          aria-labelledby="legal-modal-title"
        >
          <motion.div
            key={type}
            variants={getModalDialogVariants(durations.base)}
            initial="initial"
            animate="animate"
            exit="exit"
            onClick={(e) => e.stopPropagation()}
            className="w-full max-w-lg"
          >
            <GlassCard hoverLift={false} className="p-6">
              <div className="flex items-center justify-between gap-4 border-b border-white/10 pb-4">
                <div>
                  <h2 id="legal-modal-title" className="text-lg font-semibold text-white">
                    {isTerms ? 'Terms of Service' : 'Privacy Policy'}
                  </h2>
                  <p className="text-xs text-neutral-400">Placeholder legal notice for IDEONIX preview</p>
                </div>
                <motion.button
                  type="button"
                  onClick={onClose}
                  whileHover={{ y: -2 }}
                  whileTap={{ scale: 0.97 }}
                  transition={{ duration: durations.fast, ease: MOTION_EASING.out }}
                  aria-label="Close modal"
                  className="glass inline-flex h-10 w-10 items-center justify-center rounded-xl text-neutral-300 transition-colors hover:border-white/30 hover:text-white"
                >
                  <X className="h-4 w-4" aria-hidden="true" />
                </motion.button>
              </div>
              <div className="mt-4 space-y-3 text-sm leading-relaxed text-neutral-300">
                {isTerms ? (
                  <>
                    <p>
                      IDEONIX provides AI-assisted content planning, scripting, captioning, and scheduling
                      workflows. Outputs generated by AI models are editorial suggestions and should be
                      reviewed before publication.
                    </p>
                    <p>
                      Viral Analyzer scores are AI-generated estimates based on structural heuristics and
                      are not predictions or guarantees of social media reach.
                    </p>
                  </>
                ) : (
                  <>
                    <p>
                      When signed in with Firebase Authentication, your saved library items, brand voice
                      preferences, campaigns, and calendar entries are stored under your user account in
                      Cloud Firestore.
                    </p>
                    <p>
                      Server-side Gemini API requests are processed through IDEONIX API routes without
                      exposing keys to the browser.
                    </p>
                  </>
                )}
              </div>
              <div className="mt-6 flex justify-end">
                <GlassButton onClick={onClose}>Close</GlassButton>
              </div>
            </GlassCard>
          </motion.div>
        </motion.div>
      )}
    </AnimatePresence>
  );
}
